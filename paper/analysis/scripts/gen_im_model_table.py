#!/usr/bin/env python3
"""Generate IM prediction and paired-search SI tables from frozen reports."""
import json
from pathlib import Path
from _assets import record

PAPER = Path(__file__).resolve().parents[2]
INPUTS = ['../benchmark/im_cnn_20260914.json', '../benchmark/im_published_20260914.json']


def write(name, header, rows, desc):
    lines = ['// GENERATED by gen_im_model_table.py; do not edit.', '#table(', f'  columns: {len(header)},', '  table.header('+', '.join('['+x+']' for x in header)+'),']
    lines += ['  '+', '.join('['+str(x)+']' for x in row)+',' for row in rows]
    lines += [')']
    path = 'si/'+name+'.typ'
    (PAPER/path).write_text('\n'.join(lines)+'\n')
    record('tbl.'+name, path, kind='table', inputs=INPUTS, desc=desc)


def main():
    study = json.loads((PAPER/INPUTS[0]).read_text())
    published = json.loads((PAPER/INPUTS[1]).read_text())
    rows = []
    for cohort, values in published['cohorts'].items():
        for model, metrics in values['models'].items():
            rows.append(['Public' if cohort=='public' else 'A1', 'uno CNN' if model=='uno' else 'IM2Deep', f"{values['counts']['test']['observations']:,}", f"{metrics['median_are_percent']:.2f}", f"{metrics['p95_are_percent']:.2f}", f"{metrics['r2']:.4f}"])
    write('im-published', ['Cohort', 'Model', 'Test $n$', 'Median (%)', 'P95 (%)', '$R^2$'], rows, 'Matched held-out IM prediction accuracy with identical per-charge calibration')
    rows = []
    for cohort, values in study['study']['summary'].items():
        for arm, label in [('off', 'IM off'), ('tree_soft', 'Internal tree'), ('cnn_soft', 'uno CNN')]:
            v = values[arm]
            rows.append([cohort, label, *v['values'], v['median']])
    write('im-search', ['File', 'IM feature', 'Seed 0', 'Seed 1', 'Seed 2', 'Median'], rows, 'All 27 IM search results at 1% empirical entrapment FDP')
    rows = []
    for cohort, values in published['cohorts'].items():
        for partition, counts in values['counts'].items():
            rows.append(['Public' if cohort=='public' else 'A1', partition.title(), f"{counts['sequences']:,}", f"{counts['observations']:,}"])
    write('im-cohorts', ['Cohort', 'Partition', 'Sequences', 'Observations'], rows, 'Sequence-disjoint calibration and test partitions for the IM2Deep comparison')


if __name__ == '__main__':
    main()
