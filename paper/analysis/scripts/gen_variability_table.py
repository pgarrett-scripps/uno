#!/usr/bin/env python3
"""Generate primary seed/rerun depth summaries and per-draw calibration counts."""
import sys
import statistics
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import seed_data
import entrapment_data as ed
import style
from _assets import record


def main():
    data = seed_data.load()
    sensitivity = ["dataset\tcutoff\tuno_median\tms1_median\tmedian_ratio"]
    for ds in ed.DATASETS:
        for cutoff in (0.005, 0.01, 0.02, 0.03, 0.05, 0.10):
            uno = statistics.median(r.depth_at_entrapment(cutoff) for r in data[ds]["uno"])
            ms1 = statistics.median(r.depth_at_entrapment(cutoff) for r in data[ds]["ms1"])
            sensitivity.append(f"{ds}\t{cutoff:g}\t{uno:g}\t{ms1:g}\t{uno/ms1:.8f}")
    (style.FIGDATA / "threshold_sensitivity.tsv").write_text("\n".join(sensitivity) + "\n")
    summary = ['// Generated by gen_variability_table.py from the primary draw inventory.',
               '#table(columns: 5, align: (left, left, right, right, right),',
               'table.header(repeat: true, [Dataset], [Engine], [Draws], [1% entrapment FDR], [5% entrapment FDR]),']
    counts = ['// Generated by gen_variability_table.py; one row per primary random draw.',
              '#table(columns: 6, align: (left, left, right, right, right, right),',
              'table.header(repeat: true, [Dataset], [Draw], [Human], [Yeast], [Entrapment FDP (%)], [Depth at 1%]),']
    for ds in ed.DATASETS:
        for engine in ('uno', 'ms1'):
            runs = data[ds][engine]
            label = 'uno' if engine == 'uno' else 'ms1searchpy'
            values = []
            for cutoff in (0.01, 0.05):
                vv = [r.depth_at_entrapment(cutoff) for r in runs]
                values.append(f'{statistics.median(vv):g} ({min(vv)}-{max(vv)})')
            summary.append(f'[{ed.SHORT[ds]}], [{label}], [{len(runs)}], [{values[0]}], [{values[1]}],')
            for i, run in enumerate(runs):
                h, y, fdp = run.at_reported(0.01)
                tag = f'uno seed {run.rep}' if engine == 'uno' else f'ms1 rep {run.rep}'
                counts.append(f'[{ed.SHORT[ds] if i == 0 else ""}], [{tag}], [{h}], [{y}], [{100*fdp:.2f}], [{run.depth_at_entrapment(0.01)}],')
        summary.append('table.hline(),')
        counts.append('table.hline(),')
    for name, lines, asset in (('variability_summary', summary, 'tbl.variability-summary'),
                               ('entrap_reported', counts, 'tbl.entrap-reported')):
        lines.append(')')
        path = f'si/{name}.typ'
        (style.PAPER / path).write_text('\n'.join(lines) + '\n')
        record(asset, path, kind='table', inputs=seed_data.inputs(),
               desc='Primary random draws: depth distribution and calibration counts')


if __name__ == '__main__':
    main()
