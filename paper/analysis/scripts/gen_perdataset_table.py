#!/usr/bin/env python3
"""Generate the serialized resource cohort table (si/results_per_dataset.typ).

One row per search in `benchmark/results/summary.tsv`: the seed-0 uno search and
the three ms1searchpy replicates on each primary file, all measured serialized
on one host by `/usr/bin/time -v`. Feature counts are the line count of the
biosaur2 table each search read, minus its header.

This replaces the hand transcription the file used to carry (SUBMISSION_TODO
D1): the table is now re-derived from the summary the benchmark writes, so a
re-run cannot leave it behind.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import entrapment_data as ed  # noqa: E402
import style  # noqa: E402
from _assets import record  # noqa: E402

SUMMARY = style.BENCH / "results" / "summary.tsv"
DATA = style.BENCH / "data"
# This table has always labeled the FAIMS run by its deposit file name, as the
# prose does ("the 05433 run"), rather than by the acquisition mode the
# variability tables use.
SHORT = dict(ed.SHORT, faims_LUM2_05433_VG="05433")


def features(dataset: str) -> str:
    n = sum(1 for _ in (DATA / f"{dataset}.features.tsv").open()) - 1
    return f"{n:,}"


def main() -> int:
    rows = {}
    with SUMMARY.open() as handle:
        header = handle.readline().rstrip("\n").split("\t")
        for line in handle:
            row = dict(zip(header, line.rstrip("\n").split("\t")))
            rows.setdefault(row["dataset"], []).append(row)

    out = [
        "// Generated by analysis/scripts/gen_perdataset_table.py from",
        "// benchmark/results/summary.tsv (the serialized resource cohort) and the",
        "// biosaur2 feature tables it searched. Do not edit by hand.",
        "#table(",
        "  columns: 8,",
        "  align: (left, right, left, right, right, right, right, right),",
        "  table.header(repeat: true, [Dataset], [Features], [Engine], [1% FDR], [5% FDR],",
        "    [user-CPU (s)], [wall (s)], [peak RSS (MiB)]),",
    ]
    for dataset in ed.DATASETS:
        for i, row in enumerate(rows[dataset]):
            engine = ("uno" if row["tool"] == "uno"
                      else f"ms1searchpy rep {row['rep']}")
            first = i == 0
            out.append(
                f"  [{SHORT[dataset] if first else ''}], "
                f"[{features(dataset) if first else ''}], [{engine}], "
                f"[{row['depth_1pct']}], [{row['depth_5pct']}], "
                f"[{row['user_cpu_s']}], [{row['wall_s']}], [{row['peak_rss_mb']}],")
        if dataset != ed.DATASETS[-1]:
            out.append("  table.hline(),")
    out.append(")")

    path = "si/results_per_dataset.typ"
    (style.PAPER / path).write_text("\n".join(out) + "\n")
    inputs = [os.path.relpath(SUMMARY, style.PAPER)]
    inputs += [os.path.relpath(DATA / f"{d}.features.tsv", style.PAPER) for d in ed.DATASETS]
    record("tbl.results-per-dataset", path, kind="table", inputs=inputs,
           desc="Per-dataset depth, CPU time, wall time and peak memory for the "
                "serialized resource cohort: one uno search and three ms1searchpy "
                "searches per primary file")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
