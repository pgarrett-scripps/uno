#!/usr/bin/env python3
"""Built-in feature detection (`uno --raw`) versus biosaur2 tables.

Same search on every file, differing only in where the features came from:
the biosaur2 table used throughout the manuscript, or uno's in-process koth
feature finder reading the converted mzML directly. One panel: human proteins
at 1% entrapment FDR, both arms, per file -- the six primary files and the
12-file Astral input series (200 pg, 1 ng, 10 ng, 100 ng, three each). The 5%
depth and the 1%-list agreement stay in the summary TSV.

DATA: benchmark/results/variability_extension/summary.tsv, generated by
benchmark/variability_extension.py. Three matched seeds (0, 1, 2) per file and
arm are shown as individual points, medians, and full ranges. Zero-depth
searches are retained. Resource claims use the original serialized cohort.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

import style  # noqa: E402
from _assets import record  # noqa: E402

SUMMARY = style.BENCH / "results/variability_extension/summary.tsv"
LABEL = {
    "hela5min_09746": "09746",
    "hela5min_09766": "09766",
    "hela5min_09734": "09734",
    "hela5min_09778": "09778",
    "hela5min_09950": "09950",
    "faims_LUM2_05433_VG": "05433 (FAIMS)",
}
for _lvl, _reps in (("200pg", (1, 2, 3)), ("1ng", (1, 2, 4)), ("10ng", (1, 4, 6)), ("100ng", (2, 3, 4))):
    for _r in _reps:
        LABEL[f"astral_{_lvl}_rep{_r}"] = f"{_lvl.replace('pg', ' pg').replace('ng', ' ng')} r{_r}"
ARM = {"biosaur2": ("biosaur2 table", style.C["uno"]),
       "raw": ("built-in (--raw)", style.C["accent"])}


def depth_panel(ax, df, datasets, col, ylab, letter, legend):
    x = np.arange(len(datasets), dtype=float)
    bw = 0.36
    for k, (arm, (lab, color)) in enumerate(ARM.items()):
        for i, ds in enumerate(datasets):
            values = df[(df.dataset == ds) & (df.arm == arm)][col].astype(float).values
            if len(values) != 3:
                raise ValueError(f"need three seeds for {ds} {arm}")
            style.spread_marker(ax, x[i] + (k - 0.5) * bw, values, color,
                                jitter=0.055, half_width=0.13, ms=2.5,
                                label=lab if legend and i == 0 else None)
    ax.set_xticks(x)
    ax.set_xticklabels([LABEL[d] for d in datasets], fontsize=6.3, rotation=45, ha="right")
    ax.set_ylabel(ylab)
    ax.set_xlim(-0.6, len(datasets) - 0.4)
    ax.margins(y=0.12)
    ax.set_ylim(bottom=-65)
    ax.set_yticks([v for v in ax.get_yticks() if v >= 0])
    if letter:
        style.panel_label(ax, letter, x=-0.06)


def overlap_panel(ax, df, datasets, letter):
    x = np.arange(len(datasets), dtype=float)
    vals = [float(df[(df.dataset == d) & (df.arm == "raw")]["jaccard_1pct"].iloc[0]) for d in datasets]
    ax.bar(x, vals, 0.6, color=style.C["decoy"], edgecolor="none", zorder=2)
    for xi, v in zip(x, vals):
        ax.text(xi, v + 0.015, f"{v:.2f}", ha="center", va="bottom", fontsize=6)
    ax.set_xticks(x)
    ax.set_xticklabels([LABEL[d] for d in datasets], fontsize=6.3, rotation=45, ha="right")
    ax.set_ylabel("Jaccard index of 1% lists")
    ax.set_ylim(0, 1)
    ax.set_xlim(-0.6, len(datasets) - 0.4)
    style.panel_label(ax, letter, x=-0.13)


def main() -> int:
    df = style.read_tsv(SUMMARY)
    datasets = [d for d in LABEL if d in set(df.dataset)]
    missing = [d for d in LABEL if d not in datasets]
    if missing and not os.environ.get("FIG6_ALLOW_PARTIAL"):
        raise SystemExit(f"raw-mode summary is missing {missing}")
    for d in datasets:
        if set(df[df.dataset == d].arm) != set(ARM):
            raise SystemExit(f"{d}: need both arms")

    fig, ax = plt.subplots(1, 1, figsize=(style.W2, 2.6))
    depth_panel(ax, df, datasets, "depth_1pct", "proteins at 1% entrapment FDR", None, True)
    ax.axvline(5.5, color=style.C["light"], lw=0.8, zorder=1)
    ax.legend(loc="upper left", fontsize=6.5)
    style.save(fig, "fig5_raw_mode")
    record("fig.fig5-raw-mode", "figures/fig5_raw_mode.png", kind="figure",
           inputs=["../benchmark/results/variability_extension/summary.tsv"],
           desc="Built-in feature detection versus biosaur2 feature tables")
    record("fig.fig5-raw-mode-pdf", "figures/fig5_raw_mode.pdf", kind="figure",
           inputs=["../benchmark/results/variability_extension/summary.tsv"],
           desc="Vector twin of the built-in feature detection figure")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
