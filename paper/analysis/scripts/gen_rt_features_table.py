#!/usr/bin/env python3
"""si/rt_features.typ -- the URTC global-feature input for one worked example.

Every number is computed by importing the SAME formulas the trainer uses
(crates/uno-rt-train/python/train_rt.py: feat_global), and the generator fails
if that count disagrees with N_GLOBAL in the Rust inference path
(crates/uno-core/src/rt_cnn.rs) or with the rows described here. Nothing is
typed by hand.

Writes a bare #table into ../si/rt_features.typ; si-body.typ supplies the
caption and label.
"""

from __future__ import annotations

import os
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import numpy as np  # noqa: E402

import style  # noqa: E402
from _assets import record  # noqa: E402

TRAIN_RT = style.REPO / "crates" / "uno-rt-train" / "python" / "train_rt.py"
RT_CNN_RS = style.REPO / "crates" / "uno-core" / "src" / "rt_cnn.rs"
OUT = style.PAPER / "si" / "rt_features.typ"
PEPTIDE = "DFEAVANCINAK"

# Feature names and definitions, in the order the vector stores them: index i
# here is index i of the model input.
ROWS = [
    ("length / 50", "residues, divided by the 50-residue maximum"),
    ("acidic fraction", "D and E, per residue"),
    ("basic fraction", "K and R, per residue"),
    ("histidine fraction", "H, per residue"),
    ("hydrophobic fraction", "F W Y L I V M, per residue"),
    ("hydropathy sum / 50", "summed Kyte--Doolittle index, scaled"),
    ("hydropathy mean", "GRAVY, the per-residue mean"),
    ("aromatic fraction", "F, W and Y, per residue"),
    ("proline fraction", "P, per residue"),
    ("N-terminal hydropathy", "first residue's index, scaled"),
    ("C-terminal hydropathy", "last residue's index, scaled"),
]


def load_feat_global():
    """Import feat_global from the trainer without importing torch."""
    src = TRAIN_RT.read_text()
    start = src.index("N_GLOBAL = ")
    end = src.index("class PosMLP")
    namespace: dict = {"np": np}
    exec(compile(src[start:end], str(TRAIN_RT), "exec"), namespace)  # noqa: S102
    return namespace["feat_global"], namespace["N_GLOBAL"]


def rust_n_global() -> int:
    match = re.search(r"const N_GLOBAL: usize = (\d+);", RT_CNN_RS.read_text())
    if match is None:
        raise RuntimeError("could not find N_GLOBAL in rt_cnn.rs")
    return int(match.group(1))


def main() -> int:
    feat_global, n_global = load_feat_global()
    if n_global != rust_n_global() or n_global != len(ROWS):
        raise RuntimeError(
            f"feature count disagrees: train_rt.py {n_global}, "
            f"rt_cnn.rs {rust_n_global()}, table {len(ROWS)}")
    values = np.asarray(feat_global([PEPTIDE]), dtype=float)[0]

    lines = [
        "// GENERATED by paper/analysis/scripts/gen_rt_features_table.py -- do not edit.",
        "// Values come from the trainer's own feat_global(); the example peptide is",
        f"// {PEPTIDE}, drawn from the Chronologer holdout partition.",
        "#table(",
        "  columns: 4,",
        "  align: (right, left, left, right),",
        "  table.header([\\#], [Feature], [Definition], [Value]),",
    ]
    for i, ((name, definition), value) in enumerate(zip(ROWS, values)):
        lines.append(f"  [{i}], [{name}], [{definition}], [{value:.3f}],")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")

    inputs = [pathlib.Path(os.path.relpath(p, style.PAPER)).as_posix()
              for p in (TRAIN_RT, RT_CNN_RS)]
    record("tbl.rt-features", "si/rt_features.typ", kind="table", inputs=inputs,
           desc=f"Global physicochemical feature vector for the example peptide {PEPTIDE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
